-- FUNCTIONS AND TRIGGERS
-- ============================================

-- Function to check if a user is an admin
CREATE OR REPLACE FUNCTION is_admin()
RETURNS BOOLEAN AS $$
  SELECT EXISTS (
    SELECT 1 FROM profiles
    WHERE id = auth.uid() AND role = 'admin'
  );
$$ LANGUAGE sql SECURITY DEFINER STABLE;

-- Trigger to automatically create a profile after signup
CREATE OR REPLACE FUNCTION handle_new_user()
RETURNS TRIGGER AS $$
BEGIN
  INSERT INTO public.profiles (id, email, full_name, avatar_url)
  VALUES (
    NEW.id,
    NEW.email,
    COALESCE(NEW.raw_user_meta_data->>'full_name', NEW.raw_user_meta_data->>'name', ''),
    COALESCE(NEW.raw_user_meta_data->>'avatar_url', '')
  );
  RETURN NEW;
END;
$$ LANGUAGE plpgsql SECURITY DEFINER;

CREATE OR REPLACE TRIGGER on_auth_user_created
  AFTER INSERT ON auth.users
  FOR EACH ROW
  EXECUTE FUNCTION handle_new_user();

-- Trigger to generate a readable reservation code (e.g., AUR-1042) on insert
CREATE OR REPLACE FUNCTION generate_reservation_code()
RETURNS TRIGGER AS $$
DECLARE
  seq INTEGER;
BEGIN
  SELECT COALESCE(MAX(CAST(SUBSTRING(reservation_code FROM 5) AS INTEGER)), 999) + 1
  INTO seq FROM reservations;
  NEW.reservation_code := 'AUR-' || LPAD(seq::TEXT, 4, '0');
  RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE OR REPLACE TRIGGER set_reservation_code
  BEFORE INSERT ON reservations
  FOR EACH ROW
  WHEN (NEW.reservation_code IS NULL)
  EXECUTE FUNCTION generate_reservation_code();


-- Function to check availability for frontend query
CREATE OR REPLACE FUNCTION check_room_availability(
  p_room_type_id UUID,
  p_check_in DATE,
  p_check_out DATE,
  p_guests INTEGER DEFAULT 1
)
RETURNS TABLE (
  room_id UUID,
  room_number TEXT,
  floor INTEGER
) AS $$
BEGIN
  RETURN QUERY
  SELECT r.id, r.room_number, r.floor
  FROM rooms r
  JOIN room_types rt ON r.room_type_id = rt.id
  WHERE r.room_type_id = p_room_type_id
    AND r.status = 'available'
    AND rt.capacity >= p_guests
    AND NOT EXISTS (
      SELECT 1 FROM reservations res
      WHERE res.room_id = r.id
        AND res.status NOT IN ('cancelled')
        AND res.stay_range && daterange(p_check_in, p_check_out, '[)')
    )
  ORDER BY r.room_number;
END;
$$ LANGUAGE plpgsql STABLE;


