  FOR ALL USING (is_admin());

-- 6. Room Images Policies
CREATE POLICY "Room images are viewable by everyone" ON room_images
  FOR SELECT USING (true);

CREATE POLICY "Admins can manage room images" ON room_images
  FOR ALL USING (is_admin());

-- 7. Reservations Policies
CREATE POLICY "Users can view their own reservations" ON reservations
  FOR SELECT USING (auth.uid() = user_id OR is_admin());

CREATE POLICY "Users can insert their own reservations" ON reservations
  FOR INSERT WITH CHECK (auth.uid() = user_id);

CREATE POLICY "Users can cancel or modify their own pending/confirmed reservations" ON reservations
  FOR UPDATE USING (auth.uid() = user_id OR is_admin());

-- 8. Reservation Guests Policies
CREATE POLICY "Users can view guest info for their own reservations" ON reservation_guests
  FOR SELECT USING (
    EXISTS (
      SELECT 1 FROM reservations
      WHERE reservations.id = reservation_id AND (reservations.user_id = auth.uid() OR is_admin())
    )
  );

CREATE POLICY "Users can insert guest info for their own reservations" ON reservation_guests
  FOR INSERT WITH CHECK (
    EXISTS (
      SELECT 1 FROM reservations
      WHERE reservations.id = reservation_id AND reservations.user_id = auth.uid()
    )
  );

CREATE POLICY "Admins can manage all guest info" ON reservation_guests
  FOR ALL USING (is_admin());

-- 9. Payments Policies
CREATE POLICY "Users can view payments for their own reservations" ON payments
  FOR SELECT USING (
    EXISTS (
      SELECT 1 FROM reservations
      WHERE reservations.id = reservation_id AND (reservations.user_id = auth.uid() OR is_admin())
    )
  );

CREATE POLICY "Admins can manage all payments" ON payments
  FOR ALL USING (is_admin());

-- 10. Reviews Policies
CREATE POLICY "Reviews are viewable by everyone" ON reviews
  FOR SELECT USING (true);

CREATE POLICY "Users can insert reviews for completed stays" ON reviews
  FOR INSERT WITH CHECK (
    auth.uid() = user_id 
    AND EXISTS (
      -- Check that user actually stayed in this room type and status is checked_out
      SELECT 1 FROM reservations r
      JOIN rooms rm ON r.room_id = rm.id
      WHERE r.id = reservation_id 
        AND r.user_id = auth.uid() 
        AND rm.room_type_id = room_type_id
        AND r.status = 'checked_out'
    )
  );

CREATE POLICY "Users can update their own reviews" ON reviews
  FOR UPDATE USING (auth.uid() = user_id OR is_admin());

-- 11. Hotel Settings Policies
CREATE POLICY "Settings are viewable by everyone" ON hotel_settings
  FOR SELECT USING (true);

CREATE POLICY "Admins can manage settings" ON hotel_settings
  FOR ALL USING (is_admin());


